export type CodePage = 'CP850' | 'CP860';

/**
 * Encodes a string to raw bytes using the specified CodePage.
 * Fallbacks to ASCII/closest char if character is not in table.
 */
export function encodeCodePage(text: string, codepage: CodePage = 'CP850'): Uint8Array {
  const map = codepage === 'CP860' ? CP860_MAP : CP850_MAP;
  const bytes: number[] = [];
  
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const code = char.charCodeAt(0);
    
    if (code < 128) {
      bytes.push(code);
    } else if (map[char] !== undefined) {
      bytes.push(map[char]);
    } else {
      // Normalize accented chars if not directly in map
      const norm = char.normalize('NFD').replace(/[̀-ͯ]/g, '');
      if (norm.length > 0 && norm.charCodeAt(0) < 128) {
        bytes.push(norm.charCodeAt(0));
      } else {
        bytes.push(0x3F); // '?'
      }
    }
  }
  
  return new Uint8Array(bytes);
}
